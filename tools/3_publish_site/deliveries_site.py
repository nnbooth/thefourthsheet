def write_json(d):
    payload = {"note": "GENERATED by tools/3_publish_site/deliveries_site.py from tools/1_build_data/deliveries.py. Don't edit by hand. "
                       "Invented sample data: deliveries in and out of a Brisbane distribution centre, aggregated for the map.",
               **d["payload"]}
    (REPO / "data" / "deliveries.json").write_text(readable_json.dumps(payload) + "\n", encoding="utf-8")


